"""Copy the design's stylesheet, fonts and logos into apps/web, unchanged except for asset paths.

Run after re-importing design/. The web app's base CSS must stay identical to the design.
"""
import re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FLOW = ROOT / "design" / "flow"
WEB = ROOT / "apps" / "web"
LOGOS = {"688236c7-0c12-4a1b-a0c1-09fd44fcb378.png": "beta-mark-light.png",   # on dark surfaces
         "da914aa3-8ef8-41d4-b76f-e4910315f9e4.png": "beta-mark-dark.png"}    # on light surfaces

html = (FLOW / "index.html").read_text(encoding="utf-8")
blocks = re.findall(r"<style>(.*?)</style>", html.split("</helmet>")[0], re.S)
if len(blocks) != 2:
    sys.exit(f"expected 2 style blocks in design/flow, found {len(blocks)}")
css = "/* Generated by tools/design/sync_web_assets.py from design/flow. Do not edit. */\n" + "\n".join(blocks)
fonts = sorted(set(re.findall(r'assets/([0-9a-f-]{36}\.woff2)', css)))
css = re.sub(r'url\("assets/([0-9a-f-]{36}\.woff2)"\)', r'url("/fonts/\1")', css)
(WEB / "app").mkdir(parents=True, exist_ok=True)
(WEB / "app" / "design.css").write_text(css, encoding="utf-8")
(WEB / "public" / "fonts").mkdir(parents=True, exist_ok=True)
(WEB / "public" / "brand").mkdir(parents=True, exist_ok=True)
for f in fonts:
    shutil.copy2(FLOW / "assets" / f, WEB / "public" / "fonts" / f)
for src, dst in LOGOS.items():
    shutil.copy2(FLOW / "assets" / src, WEB / "public" / "brand" / dst)
print(f"design.css {len(css)} chars, {len(fonts)} fonts, {len(LOGOS)} logos")
