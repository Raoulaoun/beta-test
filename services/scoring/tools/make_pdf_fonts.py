"""Fixed-weight fonts for the PDF, cut once from the design's variable fonts.

WeasyPrint would otherwise instance the variable fonts on every render (seconds per PDF).
Run from services/scoring: python tools/make_pdf_fonts.py. Reads the web app's fonts
(apps/web/app/design.css and apps/web/public/fonts), writes manager_test/pdf_assets/static/*.ttf
and fonts.css. Latin and Latin Extended subsets, the weights the PDF uses.
"""
import re
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ASSETS = Path("manager_test/pdf_assets")
WEB = Path("../../apps/web")
css = (WEB / "app/design.css").read_text()
out_css, made = [], set()
(ASSETS / "static").mkdir(exist_ok=True)
for face in re.findall(r"@font-face\s*{[^}]*}", css):
    rng = re.search(r"unicode-range:\s*([^;]*);", face).group(1)
    if "U+0000-00FF" not in rng and "U+0100-02BA" not in rng:
        continue  # Latin and Latin Extended only
    family = re.search(r"font-family:\s*'([^']*)'", face).group(1)
    weight = int(re.search(r"font-weight:\s*(\d+)", face).group(1))
    src = re.search(r'url\("/fonts/([^"]*)"\)', face).group(1)
    name = f"{family.replace(' ', '')}-{weight}-{'latin' if 'U+0000-00FF' in rng else 'latinext'}.ttf"
    if name not in made:
        f = TTFont(WEB / "public/fonts" / src)
        if "fvar" in f:
            f = instantiateVariableFont(f, {"wght": weight})
        f.flavor = None
        f.save(ASSETS / "static" / name)
        made.add(name)
    out_css.append(f"@font-face {{ font-family: '{family}'; font-weight: {weight}; font-style: normal; "
                   f"src: url(\"static/{name}\") format('truetype'); unicode-range: {rng}; }}")
(ASSETS / "fonts.css").write_text("/* Generated by tools/make_pdf_fonts.py from the design's fonts. */\n" + "\n".join(out_css) + "\n")
print(len(made), "fonts")
